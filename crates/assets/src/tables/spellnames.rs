/// The name for one of them, or the number as text.
pub fn effect_name(value: u32) -> Option<&'static str> {
    lookup(&SPELL_EFFECTS, value)
}

pub fn aura_name(value: u32) -> Option<&'static str> {
    lookup(&SPELL_AURAS, value)
}

fn lookup(table: &'static [(u32, &'static str)], value: u32) -> Option<&'static str> {
    table
        .binary_search_by_key(&value, |&(at, _)| at)
        .ok()
        .map(|at| table[at].1)
}
