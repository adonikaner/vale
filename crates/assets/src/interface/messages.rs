//! **What the client says to the player** -- the 1.12.1 message table, and the
//! three things it decides that a call site must not.
//!
//! Checked by `vale messages`.
//!
//! ## What this is
//!
//! Every line the client says about the *game* -- not a cast failure and not a
//! chat line, but "Your inventory is full", "New flight path discovered!",
//! "You have learned a new ability" -- is one of 465 records the client
//! indexes by an id of its own. Each record has five columns, and **three of
//! them are decisions this client was making at the call site**:
//!
//! ```text
//! key      a GlobalStrings.lua key -- see crate::interface::strings
//! type     0 a chat line, 1 UI_INFO_MESSAGE, 2 UI_ERROR_MESSAGE, 3 chat
//! sound    a SoundEntries *name*, or the literal "NONE"
//! speech   an error-speech line 0..67, or 68 for none
//! chat     the chat type used when `type` is 0 -- 10 System, 23 Skill
//! ```
//!
//! **The surface is a column, not a judgement.** The client switches on the
//! type: cases 1 and 2 raise `UI_INFO_MESSAGE` and `UI_ERROR_MESSAGE`
//! respectively. Case 0 is a **chat line**, shown in the chat type the `chat`
//! column names. That case is **170 of the 465** -- every "X has
//! joined the party", every "You receive item:", every "You have learned" --
//! so a client that routes this table to its error frame puts a third of the
//! game's own output in the wrong window.
//!
//! **The sound is a name, and the sentinel is `"NONE"` rather than empty.**
//! The client compares the sound column against `NONE` case-insensitively,
//! and plays it by name only when they differ. That is the same by-name lookup
//! `PlaySound()` makes from Lua, so the resolution is
//! [`crate::tables::sound::SoundBank::entry_named`] and nothing new.
//!
//! **The speech column is the character's own voice**, and it is exclusive
//! with the sound rather than additional to it: the client compares the speech
//! column against 68 and takes the sound branch *only* when they are equal, so
//! a message with a speech line never plays a name sound. The speech line is
//! gated on the `EnableErrorSpeech` CVar and chosen by race and gender from 68
//! lines each -- the per-race "My bags are full" lines. **Nothing in
//! this client plays it yet**; the column is carried so that the table is the
//! whole record rather than the half that is wired up.
//!
//! ## What is not in here
//!
//! The `SPELL_FAILED_*` family is a different population with a different
//! index -- a byte on the wire into a 146-entry enum -- and none of its keys
//! appears in this table. So is `PLAYER_LOGOUT_FAILED_ERROR`. A key this table
//! does not carry is the caller's own choice of surface, which is what
//! [`Surface`] cannot answer and what `game::messages`' two older parameters
//! are still for.
//!
//! **Ids run 0..464 densely, all 465 of them**: the client accepts ids up to
//! 464, with no gaps. Every key is an `ERR_*`, and a null key shows nothing.
//! The high ids are not obscure: `ERR_MAIL_SENT`, every mail refusal,
//! `ERR_NEWTAXIPATH` and `ERR_RESTRICTED_ACCOUNT` are all in it. A key this
//! table does not carry reads as "the caller's own choice of surface", so a
//! short table would fail silently.

/// Where a message goes -- the `type` column.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Surface {
    /// A chat line, of the kind named by [`Message::chat`].
    Chat,
    /// `UI_INFO_MESSAGE` -- the yellow half of `UIErrorsFrame`.
    Info,
    /// `UI_ERROR_MESSAGE` -- the red half.
    Error,
    /// The fourth case, type 3. **No shipped row uses it**; it is
    /// here because the client has four cases and this table has three, and a
    /// reader should be able to tell those apart.
    ChatVariant,
}

/// One row of the table.
#[derive(Debug, Clone, Copy)]
pub struct Message {
    /// The client's own index. Nothing on the wire carries it; it is kept
    /// because it is what makes the table's order checkable.
    pub id: u16,
    /// The `GlobalStrings.lua` key.
    pub key: &'static str,
    pub surface: Surface,
    /// A `SoundEntries` **name**, resolved by
    /// [`crate::tables::sound::SoundBank::entry_named`].
    pub sound: Option<&'static str>,
    /// The error-speech line, 0..=67. Not played by this client -- see above.
    pub speech: Option<u8>,
    /// The chat type for [`Surface::Chat`] -- 10 is system, 23 is skill.
    pub chat: u8,
}

/// **The row for a key**, or `None` for a key this table does not carry.
///
/// Linear over 465 short strings. Every caller is a player-visible message
/// -- a refusal, a party change, a discovery -- so this runs at human rates and
/// not per-frame, and a map would cost a `OnceLock` and an allocation to save
/// nothing measurable.
pub fn message(key: &str) -> Option<&'static Message> {
    MESSAGES.iter().find(|m| m.key == key)
}

/// **The table's own structure, checked against the reader that consumes it.**
///
/// These are beside the table on purpose: they are claims about *this*
/// data, so a change to the table has to answer to them. What they cannot
/// check is the half that lives in the archives -- that every key is a real
/// `GlobalStrings.lua` key and every sound name a real `SoundEntries` row --
/// which is `vale messages`, because it needs the game files open.
#[cfg(test)]
mod tests {
    use super::*;

    /// The client indexes the table by id with no indirection, so a gap or a
    /// repeat would mean the table is wrong.
    #[test]
    fn the_ids_are_dense_and_the_keys_are_unique_err_keys() {
        for (at, message) in MESSAGES.iter().enumerate() {
            assert_eq!(usize::from(message.id), at, "{} is out of order", message.key);
            assert!(
                message.key.starts_with("ERR_"),
                "{} is not an ERR_ key",
                message.key
            );
        }
        let mut keys: Vec<_> = MESSAGES.iter().map(|m| m.key).collect();
        keys.sort_unstable();
        let before = keys.len();
        keys.dedup();
        assert_eq!(keys.len(), before, "a key appears twice");
    }

    /// **A message plays a name sound or a speech line, never both.**
    ///
    /// This is the reader's own branch rather than an observation about the
    /// data: the client compares the speech column against 68 and only falls
    /// through to the sound when they are equal. A row carrying both would be
    /// a row whose sound the client could never play -- and it is the check
    /// that says the two columns are in the right order.
    #[test]
    fn a_sound_and_a_speech_line_are_exclusive() {
        for message in &MESSAGES {
            assert!(
                message.sound.is_none() || message.speech.is_none(),
                "{} carries both a sound and a speech line",
                message.key
            );
            if let Some(speech) = message.speech {
                assert!(speech < 68, "{}: speech {speech} is past the table", message.key);
            }
        }
    }

    /// The chat column is only read for [`Surface::Chat`], and the two values
    /// the table uses are `ChatType::System` and `ChatType::Skill` -- which is
    /// a cross-check rather than a tautology, since those codes come from
    /// `crates/protocol`'s own enum and this table is the client's.
    #[test]
    fn the_chat_column_is_system_or_skill() {
        for message in &MESSAGES {
            assert!(
                message.chat == 10 || message.chat == 23,
                "{}: chat type {}",
                message.key,
                message.chat
            );
        }
        let skill: Vec<_> = MESSAGES
            .iter()
            .filter(|m| m.chat == 23)
            .map(|m| m.key)
            .collect();
        assert_eq!(
            skill,
            [
                "ERR_PROFICIENCY_GAINED_S",
                "ERR_SKILL_GAINED_S",
                "ERR_SKILL_UP_SI"
            ],
            "the skill chat type belongs to the three skill messages and nothing else"
        );
    }

    /// No shipped row takes the fourth case -- see [`Surface::ChatVariant`].
    #[test]
    fn the_fourth_surface_is_unused() {
        assert!(!MESSAGES.iter().any(|m| m.surface == Surface::ChatVariant));
    }

    /// **The row `SMSG_NEW_TAXI_PATH` shows.**
    ///
    /// `SMSG_NEW_TAXI_PATH` has no body at all: the whole packet is this row.
    #[test]
    fn the_flight_path_discovery_is_the_row_the_taxi_round_read() {
        let discovered = message("ERR_NEWTAXIPATH").expect("ERR_NEWTAXIPATH");
        assert_eq!(discovered.id, 242);
        assert_eq!(discovered.surface, Surface::Info);
        assert_eq!(discovered.sound, Some("TaxiNodeDiscovered"));
        assert_eq!(discovered.speech, None);
    }

    /// A key from the other population is absent rather than defaulted -- see
    /// the module header on what is not in here.
    #[test]
    fn a_cast_failure_is_not_in_this_table() {
        assert!(message("SPELL_FAILED_SPELL_IN_PROGRESS").is_none());
        assert!(message("PLAYER_LOGOUT_FAILED_ERROR").is_none());
        assert!(message("").is_none());
    }
}

